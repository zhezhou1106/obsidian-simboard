// Build script.
//
//   node esbuild.config.mjs              → dev: watch, inline sourcemaps
//   node esbuild.config.mjs production   → one-off release build
//
// Outputs main.js + styles.css in the repo root (the files a GitHub release
// ships). When a vault is configured (see .env.example), every successful build
// is also copied into <vault>/.obsidian/plugins/<id>/ and, if the Obsidian CLI
// is available, the plugin is hot-reloaded in the running app.

import esbuild from "esbuild";
import { builtinModules } from "node:module";
import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const prod = process.argv[2] === "production";
const root = path.dirname(new URL(import.meta.url).pathname);
const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));

// ---------- vault sync target ----------
function readEnvFile(file) {
	const out = {};
	if (!fs.existsSync(file)) return out;
	for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
		const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
		if (m && !line.trim().startsWith("#")) out[m[1]] = m[2].replace(/^["']|["']$/g, "");
	}
	return out;
}

const env = { ...readEnvFile(path.join(root, ".env.local")), ...process.env };
const vaultPath = env.OBSIDIAN_VAULT ? path.resolve(env.OBSIDIAN_VAULT.replace(/^~(?=$|\/)/, process.env.HOME || "~")) : "";
const vaultName = env.OBSIDIAN_VAULT_NAME || (vaultPath ? path.basename(vaultPath) : "");
const pluginDir = vaultPath ? path.join(vaultPath, ".obsidian", "plugins", manifest.id) : "";
const SHIPPED = ["main.js", "manifest.json", "styles.css"];

function syncToVault() {
	if (!pluginDir) return;
	if (!fs.existsSync(path.join(vaultPath, ".obsidian"))) {
		console.warn(`[sync] ${vaultPath} is not an Obsidian vault — skipped.`);
		return;
	}
	fs.mkdirSync(pluginDir, { recursive: true });
	for (const f of SHIPPED) fs.copyFileSync(path.join(root, f), path.join(pluginDir, f));
	console.log(`[sync] ${new Date().toLocaleTimeString()} → ${pluginDir}`);
	if (env.OBSIDIAN_RELOAD === "0") return;
	execFile("obsidian", [`vault=${vaultName}`, "plugin:reload", `id=${manifest.id}`], { timeout: 8000 }, (err) => {
		if (!err) console.log(`[sync] reloaded "${manifest.id}" in vault "${vaultName}"`);
	});
}

// ---------- builds ----------
let pending = 0;
let failed = false;
const syncPlugin = {
	name: "sync-to-vault",
	setup(build) {
		build.onStart(() => {
			pending++;
		});
		build.onEnd((result) => {
			pending--;
			if (result.errors.length) failed = true;
			if (pending === 0) {
				if (!failed) syncToVault();
				failed = false;
			}
		});
	},
};

const banner = `/*
${manifest.name} v${manifest.version} — ${manifest.description}
This file is generated by esbuild. Source: https://github.com/zhezhou1106/obsidian-simboard
*/
`;

const jsContext = await esbuild.context({
	banner: { js: banner },
	entryPoints: [path.join(root, "src/main.ts")],
	bundle: true,
	external: ["obsidian", "electron", "@codemirror/*", "@lezer/*", ...builtinModules],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: path.join(root, "main.js"),
	minify: false,
	plugins: [syncPlugin],
});

const cssContext = await esbuild.context({
	entryPoints: [path.join(root, "src/styles/index.css")],
	bundle: true,
	logLevel: "info",
	outfile: path.join(root, "styles.css"),
	plugins: [syncPlugin],
});

if (prod) {
	await Promise.all([jsContext.rebuild(), cssContext.rebuild()]);
	await Promise.all([jsContext.dispose(), cssContext.dispose()]);
} else {
	if (!pluginDir) console.warn("[sync] No vault configured — copy .env.example to .env.local to enable vault sync.");
	await Promise.all([jsContext.watch(), cssContext.watch()]);
}
